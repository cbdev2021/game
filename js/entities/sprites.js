const SPRITE_W = 24;

function norm(rows) {
  return rows.map((r) => {
    if (r.length > SPRITE_W) throw new Error('Row too long (' + r.length + '): ' + r);
    return (r + '........................').slice(0, SPRITE_W);
  });
}

function mirror(rows) {
  return rows.map((r) => [...r].reverse().join(''));
}

